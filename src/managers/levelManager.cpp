#include "levelManager.h"

LevelManager::LevelManager() {
  initializeLevels();
  currentLevelIndex = 0;
}

bool LevelManager::advanceLevel() {
  if (currentLevelIndex < levels.size() - 1) {
    currentLevelIndex++;
    return true;
  }
  return false;
}

